import 'package:freezed_annotation/freezed_annotation.dart';

part 'geo.freezed.dart';
part 'geo.g.dart';

/// 좌표 한 점.
/// 정본: theme-running.md 6 (`courseRoute`), run-flow.md 6 (`route`).
///
/// [t] 는 **러닝 경로에만** 채운다 — 그 좌표를 지난 시각(UTC epoch 밀리초).
/// 구간 페이스(KM splits)를 내려면 좌표마다 시각이 있어야 하는데, 이건
/// 달리는 그 순간에 적어두지 않으면 나중에 복원할 방법이 없다(2026-09-21).
///
/// 테마 코스(`ThemeRun.courseRoute`)처럼 미리 정해둔 경로는 비워 둔다 —
/// 지도에 그릴 선일 뿐이라 '몇 시에 여기 있었나'가 성립하지 않는다.
/// 그래서 필수가 아니라 선택 필드다. 예전 기록도 이 값 없이 그대로 읽힌다.
///
/// [e] 는 같은 좌표의 **달린 시간** — 러닝 시작부터의 누적 밀리초이되
/// **일시정지 시간은 빠져 있다.** 구간 페이스는 이 값으로 계산한다.
///
/// [t] 를 두고도 [e] 가 필요한 이유: [t] 는 벽시계라 쉰 시간이 그대로 들어
/// 있다. 2km 에서 5분 쉬면 그 구간만 페이스가 11'20"(실제 6'20") 로 튀고,
/// 화면에 뜨는 총 시간(쉰 시간 제외)과도 어긋난다. 둘 다 달리는 순간에만
/// 적을 수 있는 값이라 함께 남긴다(2026-09-21 사용자 결정).
///
/// [a] 는 **GPS 정확도**(미터, 반올림) — 기기가 "이 좌표는 이 반경 안쪽"
/// 이라고 알려주는 값이다. 값이 클수록 못 믿을 좌표다(트인 운동장 4m,
/// 건물 사이·야간 30m).
///
/// [s] 는 **기기가 측정한 속도**(cm/s). 두 좌표의 거리÷시간으로 낸 속도와
/// 다르다 — 그쪽은 앞뒤 좌표의 위치 오차가 둘 다 섞여 들어오는데, 이 값은
/// GPS 가 도플러로 직접 잰 것이라 위치보다 정확하다.
///
/// **둘 다 지금은 기록만 하고 거르는 데 쓰지 않는다**(2026-09-25). 2026-09-23
/// 야외 검증에서 거리가 35% 부풀었고 속도 상한(6.0 m/s)으로 한 겹 막았지만
/// 과다 계상이 남았다. 정확도로 거르는 게 더 정석인데 **이 값을 저장하지
/// 않아 임계값을 정할 근거가 없었다.** 그래서 먼저 쌓는다 — 거리를 아는
/// 코스에서 한 번 뛰면 "20m 넘는 걸 버렸으면 거리가 얼마였을까"를 실제로
/// 계산할 수 있다.
///
/// 외부 사례의 임계값: OpenTracks 기본 50m(`settings.xml`), 러닝 전용인
/// Mizutori 샘플 10m. 거리를 재는 용도는 10~30m 쪽이다.
///
/// 기기가 값을 못 준 경우는 **null 이다. 0 이 아니다.** geolocator 는
/// `hasAccuracy`/`hasSpeed` 가 false 면 자리를 0.0 으로 채워 보내는데,
/// 그걸 그대로 적으면 '오차 0m = 완벽한 좌표'로 읽혀 필터가 거꾸로 돈다.
///
/// 이름이 한 글자인 이유: 경로 한 건이 좌표 수천 개고 JSON 문자열로 통째
/// 저장·업로드된다. 키 이름이 곧 용량이다. [s] 를 m/s 소수가 아니라 cm/s
/// 정수로 두는 것도 같은 이유 — 소수점이 자릿수를 늘린다.
@freezed
abstract class LatLngPoint with _$LatLngPoint {
  const factory LatLngPoint({
    required double lat,
    required double lng,
    int? t,
    int? e,
    int? a,
    int? s,
  }) = _LatLngPoint;

  factory LatLngPoint.fromJson(Map<String, dynamic> json) =>
      _$LatLngPointFromJson(json);
}
